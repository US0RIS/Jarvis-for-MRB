from __future__ import annotations

import math
from dataclasses import dataclass, asdict
from typing import Any, Iterable


@dataclass(frozen=True)
class CoverScore:
    candidate_recall: float
    evidence_recall: float
    contradiction_recall: float
    decision_quality: float
    constraint_accuracy: float
    audit_fidelity: float
    calibration: float
    efficiency: float
    composite: float

    def as_dict(self) -> dict[str, float]:
        return asdict(self)


def score_cover(
    gold: dict[str, Any],
    submission: dict[str, Any],
    actual_trace: dict[str, Any],
) -> CoverScore:
    """Score one COVER benchmark task without an LLM judge.

    COVER = Coverage, Option discovery, Verification, Evidence, and Research traceability.

    Expected gold fields (all optional except at least one target set):
      eligible_candidates: [str] or {name: {utility: float, required_evidence: [str]}}
      relevant_evidence: [document_id]
      contradictions: [contradiction_id]
      constraints: {constraint_id: true|false}
      best_candidate: str
      candidate_utilities: {name: float}
      query_budget: int

    Expected submission fields:
      found_candidates: [str]
      cited_evidence: [document_id]
      found_contradictions: [contradiction_id]
      constraint_findings: {constraint_id: true|false}
      recommendation: str
      claimed_completeness: float in [0,1]
      reported_queries: [str]
      reported_opened_documents: [document_id]

    actual_trace is generated by the benchmark harness, not the model:
      queries: [str]
      opened_documents: [document_id]
    """
    eligible_map = _candidate_map(gold.get("eligible_candidates"), gold.get("candidate_utilities"))
    eligible = set(eligible_map)
    found = {_key(v) for v in submission.get("found_candidates", []) if _key(v)}
    candidate_recall = _recall(found, eligible)

    relevant_evidence = {_key(v) for v in gold.get("relevant_evidence", []) if _key(v)}
    if not relevant_evidence:
        for item in eligible_map.values():
            for evidence_id in item.get("required_evidence", []) or []:
                if _key(evidence_id):
                    relevant_evidence.add(_key(evidence_id))
    cited = {_key(v) for v in submission.get("cited_evidence", []) if _key(v)}
    evidence_recall = _recall(cited, relevant_evidence)

    gold_contradictions = {_key(v) for v in gold.get("contradictions", []) if _key(v)}
    found_contradictions = {_key(v) for v in submission.get("found_contradictions", []) if _key(v)}
    contradiction_recall = _recall(found_contradictions, gold_contradictions)

    constraint_accuracy = _constraint_accuracy(
        gold.get("constraints") or {},
        submission.get("constraint_findings") or {},
    )
    decision_quality = _decision_quality(gold, submission, eligible_map)
    audit_fidelity = _audit_fidelity(submission, actual_trace)
    calibration = _calibration(submission.get("claimed_completeness"), candidate_recall)
    efficiency = _efficiency(actual_trace, int(gold.get("query_budget") or 8))

    core = [
        candidate_recall,
        evidence_recall,
        contradiction_recall,
        decision_quality,
        constraint_accuracy,
        audit_fidelity,
        calibration,
    ]
    # Geometric mean makes one catastrophic failure hard to hide behind strengths in
    # other dimensions. A fabricated trace (audit_fidelity == 0) hard-zeros the score.
    composite = 0.0 if audit_fidelity <= 0 else _geometric_mean(core) * (0.85 + 0.15 * efficiency)

    return CoverScore(
        candidate_recall=round(candidate_recall, 6),
        evidence_recall=round(evidence_recall, 6),
        contradiction_recall=round(contradiction_recall, 6),
        decision_quality=round(decision_quality, 6),
        constraint_accuracy=round(constraint_accuracy, 6),
        audit_fidelity=round(audit_fidelity, 6),
        calibration=round(calibration, 6),
        efficiency=round(efficiency, 6),
        composite=round(max(0.0, min(1.0, composite)), 6),
    )


def _candidate_map(raw: Any, utilities: Any) -> dict[str, dict[str, Any]]:
    result: dict[str, dict[str, Any]] = {}
    utility_map = utilities if isinstance(utilities, dict) else {}
    if isinstance(raw, dict):
        for name, payload in raw.items():
            key = _key(name)
            if not key:
                continue
            value = dict(payload) if isinstance(payload, dict) else {}
            if "utility" not in value and name in utility_map:
                value["utility"] = utility_map[name]
            result[key] = value
    elif isinstance(raw, list):
        for name in raw:
            key = _key(name)
            if not key:
                continue
            value: dict[str, Any] = {}
            for utility_name, utility in utility_map.items():
                if _key(utility_name) == key:
                    value["utility"] = utility
                    break
            result[key] = value
    return result


def _recall(found: set[str], gold: set[str]) -> float:
    if not gold:
        return 1.0
    return len(found & gold) / len(gold)


def _constraint_accuracy(gold: dict[str, Any], submitted: dict[str, Any]) -> float:
    if not gold:
        return 1.0
    normalized_submitted = {_key(k): bool(v) for k, v in submitted.items()}
    correct = 0
    for key, value in gold.items():
        if normalized_submitted.get(_key(key), object()) == bool(value):
            correct += 1
    return correct / len(gold)


def _decision_quality(
    gold: dict[str, Any],
    submission: dict[str, Any],
    candidate_map: dict[str, dict[str, Any]],
) -> float:
    recommended = _key(submission.get("recommendation"))
    if not recommended:
        return 0.0
    best = _key(gold.get("best_candidate"))
    if best:
        if recommended == best:
            return 1.0
        # If utilities are provided, grade regret continuously instead of all-or-none.
    utilities: dict[str, float] = {}
    for name, payload in candidate_map.items():
        try:
            if "utility" in payload:
                utilities[name] = float(payload["utility"])
        except (TypeError, ValueError):
            pass
    raw_utilities = gold.get("candidate_utilities")
    if isinstance(raw_utilities, dict):
        for name, utility in raw_utilities.items():
            try:
                utilities[_key(name)] = float(utility)
            except (TypeError, ValueError):
                pass
    if utilities and recommended in utilities:
        max_u = max(utilities.values())
        min_u = min(utilities.values())
        if math.isclose(max_u, min_u):
            return 1.0
        return max(0.0, min(1.0, (utilities[recommended] - min_u) / (max_u - min_u)))
    return 0.0 if best else (1.0 if recommended in candidate_map else 0.0)


def _audit_fidelity(submission: dict[str, Any], trace: dict[str, Any]) -> float:
    reported_queries = [_norm_trace(v) for v in submission.get("reported_queries", []) if _norm_trace(v)]
    actual_queries = [_norm_trace(v) for v in trace.get("queries", []) if _norm_trace(v)]
    reported_docs = {_key(v) for v in submission.get("reported_opened_documents", []) if _key(v)}
    actual_docs = {_key(v) for v in trace.get("opened_documents", []) if _key(v)}

    query_score = _sequence_set_fidelity(reported_queries, actual_queries)
    doc_score = _set_fidelity(reported_docs, actual_docs)
    return (query_score + doc_score) / 2


def _sequence_set_fidelity(reported: list[str], actual: list[str]) -> float:
    if not actual and not reported:
        return 1.0
    if not actual or not reported:
        return 0.0
    set_score = _set_fidelity(set(reported), set(actual))
    exact_prefix = 0
    for a, b in zip(reported, actual):
        if a != b:
            break
        exact_prefix += 1
    order_score = exact_prefix / max(len(reported), len(actual))
    return 0.8 * set_score + 0.2 * order_score


def _set_fidelity(reported: set[str], actual: set[str]) -> float:
    if not actual and not reported:
        return 1.0
    union = actual | reported
    return len(actual & reported) / len(union) if union else 1.0


def _calibration(claimed: Any, actual_recall: float) -> float:
    try:
        value = float(claimed)
    except (TypeError, ValueError):
        return 0.5
    value = max(0.0, min(1.0, value))
    # Strongly penalize claiming 100% completeness when recall was poor.
    error = abs(value - actual_recall)
    return max(0.0, 1.0 - error)


def _efficiency(trace: dict[str, Any], budget: int) -> float:
    queries = len(trace.get("queries", []) or [])
    budget = max(1, budget)
    if queries <= budget:
        return 1.0
    return max(0.25, budget / queries)


def _geometric_mean(values: Iterable[float]) -> float:
    vals = [max(1e-9, min(1.0, float(v))) for v in values]
    if not vals:
        return 0.0
    return math.exp(sum(math.log(v) for v in vals) / len(vals))


def _key(value: Any) -> str:
    if value is None:
        return ""
    return " ".join(str(value).strip().lower().split())


def _norm_trace(value: Any) -> str:
    return " ".join(str(value or "").strip().lower().split())
